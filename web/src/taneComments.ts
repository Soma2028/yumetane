export function taneComment(mostStudied: SubjectTotal | null): string {
  if (!mostStudied) return "まだ記録がないよ。今日の勉強を記録してみよう。"
  const patterns = SUBJECT_COMMENTS[mostStudied.subject]
  if (!patterns || patterns.length === 0) {
    return `${mostStudied.subject}をよく勉強してるね！新しい仕事にたくさん出会えそう！`
  }
  return patterns[mostStudied.minutes % patterns.length]
}
